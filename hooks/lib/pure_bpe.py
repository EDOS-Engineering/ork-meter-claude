"""Exact o200k_base token counts in pure Python, for when tiktoken is missing (#115).

Reproduces ``token_gate``'s pinned encoding's ``encode_ordinary``: the bundled,
hash-checked ``o200k_base`` vocabulary and ``token_gate.PATTERN``, with no
special tokens. Standard library only; tests/pure_bpe_regressions.py compares
it with tiktoken on a large corpus and seeded fuzzing.

Pre-tokenization. ``PATTERN`` needs ``\\p{..}`` classes, which ``re`` lacks. Each
character is first mapped to a one-character class code (``_code``), and an
equivalent pattern over those codes (``_CODE_PATTERN``) runs on the code string
with ``re``. Both engines are leftmost-first backtracking matchers and the
mapping keeps lengths, so the matches are tiktoken's pieces. The codes keep
what the pattern can tell apart: the letter classes, marks, numbers, the
regex crate's ``\\s`` (Unicode White_Space, not ``str.isspace``, which adds
U+001C..U+001F), CR, LF, the space, ``/``, the apostrophe and the contraction
letters (``(?i)s`` also matches U+017F LONG S under Unicode simple case
folding). General categories come from ``_CATEGORIES``, pinned to the Unicode
version of tiktoken 0.14.0's regex crate, not from this interpreter's
``unicodedata``, which differs across Python versions.

Merging. Like tiktoken: a piece that is a token is that token; otherwise, from
one part per byte, repeatedly merge the adjacent pair whose joined bytes have
the lowest rank (the leftmost on ties) until no pair is a token. Short pieces
use tiktoken's list scan; long ones a heap over a linked list.

``encoder()`` loads the vocabulary through ``token_gate.load_ranks``, the one
loader and integrity check every exact encoder shares, in about 50 ms
(decompression, the SHA-256 check and the rank table), about 70 ms with the
import; ``token_gate.encoding`` keeps the encoder for the process. Typical
text then encodes at about 0.2 ms per KiB. ``MAX_PIECE_BYTES`` and
``MAX_MERGE_BYTES`` bound the time adversarial text (long runs of one
character) can take: past them, ``encode`` raises ValueError so the gate
refuses instead of stalling.
"""
